# integer
print(8)
print(1e308)
print(1e309)


# decimal/float
print(8.55)
print(1.7e308)
print(1.7e309)


# boolean
print(True)
print(False)


# text/string
print("Hello World")


# complex
print(5 + 6j)
print(1e308 + 1e308j)
print(1e309 + 1e309j)


# list
print([1, 2, 3, 4, 5])


# tuple
print((1, 2, 3, 4, 5))


# sets
print({1, 2, 3, 4, 5})


# dictionary
dict = {"Name": "Aryan", "Gender": "Male", "Weight": 70}
print(dict)


# type
print(type(3.5))
print(type(3))
print(type("Aryan"))
print(type(3 + 5j))
print(type([1, 2, 3]))
