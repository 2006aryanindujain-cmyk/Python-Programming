# Keywords are the reserved words that has some specific meaning in that language.


# Python is an interpreted language.


# Keywords cannot be used as identifier name.


# Identifiers are the names given by the programmer to the variable, object and functions.


# identifiers cannot start with a digit.
name1 = "Aryan"
print(name1)


# We can use onle '_' special character in naming identifiers.
_ = "Aryan"
print(_)


# Identifiers cannot be keywords.


# Identifiers only contain digits, alphabets, underscore(_).


